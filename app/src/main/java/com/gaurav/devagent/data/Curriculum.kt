package com.gaurav.devagent.data

import kotlinx.serialization.Serializable

@Serializable
enum class Track(val label: String, val short: String) {
    DSA("DSA problem", "DSA"),
    SYSTEM_DESIGN("System design", "SD"),
    AI("AI course", "AI"),
}

/** One day's item in a track. [tag] is the short subtitle shown on the widget. */
data class Lesson(
    val title: String,
    val url: String,
    val tag: String,
    val summary: String = "",
    val task: String = "",
)

/**
 * Position in a track. An item stays "today's item" until it is marked done;
 * the day after it was done, the next item appears. Skipped days don't skip content.
 */
@Serializable
data class TrackProgress(val index: Int = 0, val doneOn: String? = null)

data class DailyItem(val track: Track, val number: Int, val total: Int, val lesson: Lesson, val done: Boolean)

object Curriculum {
    fun lessons(track: Track): List<Lesson> = when (track) {
        Track.DSA -> DSA_PROBLEMS
        Track.SYSTEM_DESIGN -> SYSTEM_DESIGN_LESSONS
        Track.AI -> AI_COURSE
    }

    /** Index of the item to show today (wraps around at the end of a track). */
    fun currentIndex(track: Track, p: TrackProgress): Int {
        val raw = if (p.doneOn != null && p.doneOn != today()) p.index + 1 else p.index
        return raw.mod(lessons(track).size)
    }

    fun todayItems(state: AgentState): List<DailyItem> = Track.entries.map { track ->
        val p = state.progress[track] ?: TrackProgress()
        val index = currentIndex(track, p)
        val all = lessons(track)
        DailyItem(track, index + 1, all.size, all[index], done = p.doneOn == today() && p.index == index)
    }

    fun toggled(track: Track, p: TrackProgress): TrackProgress {
        val index = currentIndex(track, p)
        val doneToday = p.doneOn == today() && p.index == index
        return TrackProgress(index, if (doneToday) null else today())
    }

    /** Moves today's item forward or back without marking anything done. */
    fun moved(track: Track, p: TrackProgress, delta: Int): TrackProgress =
        TrackProgress((currentIndex(track, p) + delta).mod(lessons(track).size), null)
}

